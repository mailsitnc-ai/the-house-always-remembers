import { Vector3 } from "@babylonjs/core/Maths/math.vector";
import type { AudioManager } from "../atmosphere/AudioManager";
import type { RecordingDef } from "./StoryData";
import { VOICES } from "./DialogueVoices";

interface ManifestClip {
  file: string;
  duration: number;
}

export interface DialogueSchedule {
  /** Audio-clock time the recording begins. */
  startTime: number;
  /** Start and end of each line, in seconds after startTime. Taken from the real clip lengths. */
  starts: number[];
  ends: number[];
  total: number;
  /** False when no audio could be played and only subtitles will run. */
  audible: boolean;
  stop(): void;
}

const MAX_CACHED_CLIPS = 24;
const LINE_GAP = 0.45;

/** Rough spoken length, for subtitles when a clip or the audio system is unavailable. */
export function estimateSeconds(text: string): number {
  return 0.7 + text.split(/\s+/).length * 0.36;
}

/**
 * Plays recorded dialogue clips with subtitle timing that comes from the real clip lengths. Clips are small AAC files
 * generated by tools/generate-dialogue.mjs (or replaced by real recordings with the same names). They are fetched on
 * demand, decoded, and kept in a small cache so memory stays low. If a clip or the audio system fails, the recording still
 * runs as subtitles so the story never depends on sound.
 */
export class DialogueSystem {
  private manifest: Record<string, ManifestClip> | null = null;
  private manifestLoading: Promise<void> | null = null;
  private readonly cache = new Map<string, { buffer: AudioBuffer; used: number }>();
  private impulse: AudioBuffer | null = null;
  private tick = 0;
  /** Counts failures, for the status line. */
  failures = 0;

  constructor(private readonly audio: AudioManager) {}

  private async loadManifest(): Promise<void> {
    if (this.manifest) return;
    this.manifestLoading ??= (async () => {
      try {
        const r = await fetch(`${import.meta.env.BASE_URL}audio/dialogue/manifest.json`);
        const j = (await r.json()) as { clips: Record<string, ManifestClip> };
        this.manifest = j.clips;
      } catch {
        this.manifest = {};
      }
    })();
    await this.manifestLoading;
  }

  private async buffer(key: string): Promise<AudioBuffer | null> {
    const hit = this.cache.get(key);
    if (hit) {
      hit.used = ++this.tick;
      return hit.buffer;
    }
    const ctx = this.audio.context;
    const clip = this.manifest?.[key];
    if (!ctx || !clip) return null;
    try {
      const r = await fetch(`${import.meta.env.BASE_URL}audio/dialogue/${clip.file}`);
      if (!r.ok) throw new Error(String(r.status));
      const buffer = await ctx.decodeAudioData(await r.arrayBuffer());
      this.cache.set(key, { buffer, used: ++this.tick });
      if (this.cache.size > MAX_CACHED_CLIPS) {
        let oldest: string | null = null;
        for (const [k, v] of this.cache) if (oldest === null || v.used < this.cache.get(oldest)!.used) oldest = k;
        if (oldest) this.cache.delete(oldest);
      }
      return buffer;
    } catch {
      this.failures++;
      return null;
    }
  }

  /** Fetches and decodes the clips of a recording ahead of time. */
  async preload(rec: RecordingDef): Promise<void> {
    await this.loadManifest();
    await Promise.all(rec.lines.map((_, i) => this.buffer(`${rec.id}#${i}`)));
  }

  /** Starts a recording. `position` (world space) makes it come from a place in the house. */
  async play(rec: RecordingDef, lead: number, position?: Vector3): Promise<DialogueSchedule> {
    await this.loadManifest();
    const ctx = this.audio.context;
    const out = this.audio.dialogueOut;
    const buffers = ctx && out ? await Promise.all(rec.lines.map((_, i) => this.buffer(`${rec.id}#${i}`))) : rec.lines.map(() => null);
    const audible = !!ctx && !!out && buffers.some((b) => b);
    const now = this.audio.now();
    const startTime = now + 0.12;
    const starts: number[] = [];
    const ends: number[] = [];
    let cursor = lead;
    rec.lines.forEach((line, i) => {
      const b = buffers[i];
      const pitch = VOICES[line.voice]?.pitch ?? 1;
      const d = b ? b.duration / pitch : estimateSeconds(line.text);
      starts.push(cursor);
      ends.push(cursor + d);
      cursor += d + LINE_GAP;
    });
    const total = cursor;
    if (!audible || !ctx || !out) return { startTime, starts, ends, total, audible: false, stop: () => undefined };

    const chain = this.buildChain(ctx, out, rec.medium, position);
    const sources: AudioBufferSourceNode[] = [];
    rec.lines.forEach((line, i) => {
      const b = buffers[i];
      if (!b) return;
      const profile = VOICES[line.voice];
      const src = ctx.createBufferSource();
      src.buffer = b;
      src.playbackRate.value = profile?.pitch ?? 1;
      if (rec.medium === "tape" || rec.medium === "machine") {
        // A little tape wobble.
        const lfo = ctx.createOscillator();
        lfo.frequency.value = 0.6 + (i % 3) * 0.2;
        const depth = ctx.createGain();
        depth.gain.value = 9;
        lfo.connect(depth).connect(src.detune);
        lfo.start(ctx.currentTime + startTime - now + starts[i]);
        lfo.stop(ctx.currentTime + startTime - now + ends[i] + 0.1);
      }
      const g = ctx.createGain();
      g.gain.value = (profile?.gain ?? 1) * (line.voice === "fake" ? 0.9 : 1);
      src.connect(g).connect(chain.input);
      src.start(startTime + starts[i]);
      sources.push(src);
    });
    if (rec.medium === "machine") chain.beep(startTime + Math.max(0, lead - 0.4));
    chain.begin(startTime, startTime + total);
    return {
      startTime,
      starts,
      ends,
      total,
      audible: true,
      stop: () => {
        const t = ctx.currentTime;
        chain.input.gain.cancelScheduledValues(t);
        chain.input.gain.setTargetAtTime(0, t, 0.04);
        for (const s of sources) {
          try {
            s.stop(t + 0.2);
          } catch {
            /* already stopped */
          }
        }
        chain.end(t + 0.25);
      },
    };
  }

  /**
   * The sound of the place the voice comes from: a telephone line, a tape, an answering machine, a room, or Daniel's head.
   * Returns the input to connect clips to, and hooks to start and stop the noise that belongs to the medium.
   */
  private buildChain(ctx: AudioContext, out: AudioNode, medium: RecordingDef["medium"], position?: Vector3) {
    const input = ctx.createGain();
    const nodes: AudioScheduledSourceNode[] = [];
    let tail: AudioNode = input;
    const filter = (type: BiquadFilterType, f: number, q = 0.7) => {
      const n = ctx.createBiquadFilter();
      n.type = type;
      n.frequency.value = f;
      n.Q.value = q;
      tail.connect(n);
      tail = n;
    };
    const reverb = (wet: number) => {
      const conv = ctx.createConvolver();
      conv.buffer = (this.impulse ??= this.makeImpulse(ctx, 1.4));
      const wetGain = ctx.createGain();
      wetGain.gain.value = wet;
      const sum = ctx.createGain();
      tail.connect(sum);
      tail.connect(conv);
      conv.connect(wetGain).connect(sum);
      tail = sum;
    };
    let hissLevel = 0;
    if (medium === "phone") {
      filter("highpass", 380);
      filter("lowpass", 3100);
      const shaper = ctx.createWaveShaper();
      const curve = new Float32Array(256);
      for (let i = 0; i < 256; i++) curve[i] = Math.tanh(((i / 255) * 2 - 1) * 2.2);
      shaper.curve = curve;
      tail.connect(shaper);
      tail = shaper;
      hissLevel = 0.012;
    } else if (medium === "tape") {
      filter("highpass", 180);
      filter("lowpass", 5200);
      hissLevel = 0.018;
    } else if (medium === "machine") {
      filter("highpass", 260);
      filter("lowpass", 4200);
      hissLevel = 0.012;
    } else if (medium === "inner") {
      filter("lowpass", 4600);
      reverb(0.32);
    } else {
      reverb(0.2);
    }
    let dest: AudioNode = out;
    if (position) {
      const p = ctx.createPanner();
      p.panningModel = "HRTF";
      p.distanceModel = "inverse";
      p.refDistance = 2;
      p.rolloffFactor = 1.1;
      p.positionX.value = position.x;
      p.positionY.value = position.y;
      p.positionZ.value = -position.z;
      p.connect(out);
      dest = p;
    }
    const gate = ctx.createGain();
    tail.connect(gate).connect(dest);
    let hiss: AudioBufferSourceNode | null = null;
    return {
      input,
      beep: (at: number) => {
        const o = ctx.createOscillator();
        o.frequency.value = 1000;
        const g = ctx.createGain();
        g.gain.setValueAtTime(0, at);
        g.gain.linearRampToValueAtTime(0.12, at + 0.01);
        g.gain.setValueAtTime(0.12, at + 0.2);
        g.gain.linearRampToValueAtTime(0, at + 0.23);
        o.connect(g).connect(dest);
        o.start(at);
        o.stop(at + 0.3);
        nodes.push(o);
      },
      begin: (from: number, to: number) => {
        const noise = this.audio.noiseBuffer;
        if (!hissLevel || !noise) return;
        hiss = ctx.createBufferSource();
        hiss.buffer = noise;
        hiss.loop = true;
        const lp = ctx.createBiquadFilter();
        lp.type = "lowpass";
        lp.frequency.value = medium === "phone" ? 3000 : 6000;
        const g = ctx.createGain();
        g.gain.value = hissLevel;
        hiss.connect(lp).connect(g).connect(dest);
        hiss.start(from);
        hiss.stop(to);
      },
      end: (at: number) => {
        try {
          hiss?.stop(at);
        } catch {
          /* ignore */
        }
        for (const n of nodes) {
          try {
            n.stop(at);
          } catch {
            /* ignore */
          }
        }
      },
    };
  }

  /** A synthetic room impulse: decaying noise. Small and cheap, and enough to place a voice in a room. */
  private makeImpulse(ctx: AudioContext, seconds: number): AudioBuffer {
    const len = Math.floor(ctx.sampleRate * seconds);
    const buf = ctx.createBuffer(2, len, ctx.sampleRate);
    for (let c = 0; c < 2; c++) {
      const d = buf.getChannelData(c);
      for (let i = 0; i < len; i++) d[i] = (Math.random() * 2 - 1) * Math.pow(1 - i / len, 2.6);
    }
    return buf;
  }
}
